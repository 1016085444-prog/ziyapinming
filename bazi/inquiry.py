"""盘上「需结合处境才能定论」的点。

这是转化引擎，但有一条自己划死的线：**每一条都必须是真的两可**。

同一个结构在不同处境下走法相反——官杀混杂在体制内是路径不清、在体制外是
攻守兼备；日支逢冲在朝九晚五是聚少离多、在出差型工作反而是解。这类分岔
盘面本身答不了，必须知道当事人的实际处境。

不做的事：把已知结论藏起来假装神秘，或者「你命里有一处凶险，加微信详谈」
这种制造恐惧的话术。除了不体面，它招来的是最焦虑、最难伺候、最容易事后
翻脸的客户，对靠复购和转介绍的生意是负资产。

每条给三段：盘上的事实 → 为什么两可 → 一个只有当事人能答的问题。
"""

from __future__ import annotations

from .analysis import day_master_strength, element_scores, ten_god_census

__all__ = ["open_questions", "MAX_QUESTIONS"]

# 超过三条会稀释注意力，反而没有一条被认真对待
MAX_QUESTIONS = 3


def _luck_turning(chart, this_year):
    """是否临近大运交接（前后两年内）。换运前后该进该守，最看当下手上的事。"""
    for lp in chart.luck_pillars:
        if abs(lp.start_year - this_year) <= 2:
            return lp
    return None


def open_questions(chart, this_year=None):
    """返回至多 MAX_QUESTIONS 条待定论的点，按冲击力排序。"""
    import time
    if this_year is None:
        this_year = time.localtime().tm_year

    strength = day_master_strength(chart)
    census = ten_god_census(chart)
    scores, _ = element_scores(chart)
    roles = strength["五行角色"]
    total = sum(scores.values()) or 1.0
    r = {k: scores[v] / total for k, v in roles.items()}
    balance = strength["扶抑比"]
    god = lambda n: census.get(n, 0.0)          # noqa: E731

    male = chart.gender == "male"
    day_branch = chart.day.branch
    others = [p.branch for p in chart.pillars if p is not chart.day]

    from .ganzhi import SIX_CLASH
    day_clashed = any(frozenset((day_branch, b)) in SIX_CLASH for b in others)

    out = []

    # ── 官杀混杂：两种权力关系，体制内外走法相反 ──────────────
    if god("正官") > 0.5 and god("七杀") > 0.5:
        out.append((100, {
            "标题": "正官七杀并见",
            "问法": "我盘上正官七杀并见，体制内和自己干，哪条更适合我？",
            "事实": "你的盘上正官与七杀同现。这是两种完全不同的权力关系——"
                    "一种讲规矩、名分与流程，一种讲魄力、决断与搏杀。",
            "两可": "在层级分明的组织里，这是路径分岔、容易两头不靠；"
                    "在自己说了算的场子里，这反而是攻守两手都有。",
            "问题": "你现在是在讲规矩的地方，还是在自己说了算的地方？",
        }))

    # ── 财旺身弱：守成还是借力扩张 ────────────────────────────
    if r["财"] > 0.26 and balance < 0.44:
        out.append((92, {
            "标题": "财旺而日主偏弱",
            "问法": "我财旺身弱，眼下这一步该守成还是该放大？",
            "事实": "机会不缺，难在你这一头的承载力——盘上财星旺，"
                    "日主却偏弱，典型的「看得见、抓不稳」。",
            "两可": "手上已有平台或靠山的，这一步该借力放大；"
                    "光靠自己单扛的，此时扩张多半是替别人做嫁衣。",
            "问题": "你现在手上，有没有一个能借的平台或人？",
        }))

    # ── 伤官见官：同一特质，行业不同结果相反 ──────────────────
    if god("伤官") > 0.8 and god("正官") > 0.5:
        out.append((88, {
            "标题": "伤官见官",
            "问法": "我伤官见官，现在这个行业到底适不适合我？",
            "事实": "你的表达欲、主见和不服管，在盘上是明写着的。",
            "两可": "在创意、内容、技术这类看结果的行业，这是核心竞争力；"
                    "在讲究序列和分寸的地方，同样这股劲会变成硬伤。",
            "问题": "你所在的行业，是看结果，还是看规矩？",
        }))

    # ── 日支逢冲：婚姻还是职业形态 ────────────────────────────
    if day_clashed:
        out.append((85, {
            "标题": "配偶宫逢冲",
            "问法": "我配偶宫逢冲，感情上具体该注意什么？",
            "事实": "日支是配偶宫，你这一柱被冲，主关系里聚散反复、"
                    "或长期分处两地。",
            "两可": "朝九晚五的生活里，这确实是消耗；"
                    "但若本就是出差、外派、异地这类职业形态，"
                    "冲反而被工作消化掉了，未必落到感情上。",
            "问题": "你和伴侣现在是天天见面，还是本来就聚少离多？",
        }))

    # ── 比劫重：合伙还是单干 ──────────────────────────────────
    if r["比劫"] > 0.32:
        out.append((80, {
            "标题": "比劫偏重",
            "问法": "我比劫偏重，这个合伙能不能做、条件该怎么谈？",
            "事实": "平辈的助力与竞争在你盘上是同一股力量，分不开。",
            "两可": "分工清楚、权责写在纸上的合作，这是最好的助推；"
                    "含糊其辞的「兄弟一起干」，同样这股力量会变成分账时的麻烦。",
            "问题": "你眼下有没有正在谈或已经在做的合伙？条件谈到哪一步了？",
        }))

    # ── 印重：依靠还是拖累 ────────────────────────────────────
    if r["印"] > 0.30 and balance > 0.56:
        out.append((74, {
            "标题": "印星偏重而日主已旺",
            "问法": "我印重身旺，家里给的安排该不该接？",
            "事实": "盘上照应你的力量很足，但日主本身也不弱，"
                    "扶过头了反而滞。",
            "两可": "这份照应若来自能给资源的长辈或平台，是实打实的起点；"
                    "若来自事事替你安排的关系，那就是绑住手脚的东西。",
            "问题": "现在最影响你决定的那个人，是给你资源，还是替你拿主意？",
        }))

    # ── 换运临界：进还是守 ────────────────────────────────────
    lp = _luck_turning(chart, this_year)
    if lp is not None:
        out.append((70, {
            "标题": "正处大运交接前后",
            "问法": "我 {} 年前后交入 {} 运，手上的事该收口还是该转向？".format(lp.start_year, lp.gz),
            "事实": "{} 年前后你交入 {} 运，这是十年一换的节点。".format(
                lp.start_year, lp.gz),
            "两可": "手上有正在推进、只差临门一脚的事，换运前后宜稳住收口；"
                    "手上是长期不见起色的局面，这个节点恰恰是掀桌重来的时机。",
            "问题": "你手上现在的事，是快成了，还是拖了很久没动静？",
        }))

    # ── 调候失衡：地域是可调变量 ──────────────────────────────
    if chart.month.branch in "亥子丑" and scores["火"] / total < 0.08:
        out.append((62, {
            "标题": "生于冬月而火气不足",
            "问法": "我盘寒而火弱，住哪、做什么行业能补回来？",
            "事实": "你的盘寒气偏重，缺的是暖。这在体感、循环和情绪上都会显。",
            "两可": "命理上补火最实在的两条路是地域和职业——"
                    "南方与北方、向阳与背阴，对这类盘的差别不是玄学，是体感。",
            "问题": "你现在长住在哪？是偏南还是偏北？",
        }))
    elif chart.month.branch in "巳午未" and scores["水"] / total < 0.08:
        out.append((62, {
            "标题": "生于夏月而水气不足",
            "问法": "我盘燥而水弱，地域和作息该怎么调？",
            "事实": "你的盘燥气偏重，缺的是润。易耗、易急、睡不深。",
            "两可": "补水同样落在地域与作息上，近水与不近水、"
                    "熬夜与不熬夜，对这类盘是两种状态。",
            "问题": "你现在住的地方近水吗？作息是几点睡？",
        }))

    # ── 食伤旺而财轻：才华与变现渠道 ──────────────────────────
    if r["食伤"] > 0.26 and r["财"] < 0.12:
        out.append((58, {
            "标题": "食伤旺而财星偏轻",
            "问法": "我食伤旺、财星轻，手上的东西该怎么变现？",
            "事实": "才气有，出口不畅——盘上产出的力量足，接住它的财星却轻。",
            "两可": "有稳定渠道或平台把作品送出去的，这是厚积；"
                    "没有渠道的，容易一直停在「东西很好，就是没人知道」。",
            "问题": "你做的东西，现在有固定的地方发布或交付吗？",
        }))

    # ── 兜底：上面全不触发的盘约占 5%，那些用户看完一个钩子都没有。
    #    任何人都在某一步大运里，也都有喜忌，所以这两条必定成立。 ──────
    from .analysis import favorable_elements
    from .ganzhi import ten_god

    cur = chart.luck_at(this_year)
    if cur is not None:
        out.append((40, {
            "标题": "当前所行 {} 运".format(cur.gz),
            "问法": "我现在走 {} 运，这十年该往哪个方向用？".format(cur.gz),
            "事实": "你眼下走在 {} 运（{}），天干于你是{}。".format(
                cur.gz, "{}–{}".format(cur.start_year, cur.end_year),
                ten_god(chart.day_stem, cur.stem)),
            "两可": "同一步运，用来守住现有的摊子，还是用来换方向，"
                    "十年后的结果差得很远。运只给势，不替人做选择。",
            "问题": "接下来一两年，你是想稳住现在这摊，还是想动一动？",
        }))
    else:
        fav = favorable_elements(chart)
        out.append((38, {
            "标题": "喜用在{}".format("、".join(fav["喜用"])),
            "问法": "我喜用在{}，职业、地域、身边人这三条该先动哪一条？".format("、".join(fav["喜用"])),
            "事实": "你的盘喜{}。{}".format(
                "、".join(fav["喜用"]), fav["取用依据"]),
            "两可": "补喜用最实在的路径无非职业、地域、身边的人这三条，"
                    "但哪一条对你可行，取决于你现在的条件。",
            "问题": "这三条里，你现在最能动的是哪一条？",
        }))

    out.sort(key=lambda x: -x[0])
    return [q for _, q in out[:MAX_QUESTIONS]]
