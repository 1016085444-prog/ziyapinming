# 儒略日
# --------------------------------------------------------------------------

def julian_day(dt):
    """UTC datetime → 儒略日（含小数）。1582-10-15 起用格里历。"""
    y, m = dt.year, dt.month
    day = (
        dt.day
        + (dt.hour + (dt.minute + (dt.second + dt.microsecond / 1e6) / 60.0) / 60.0)
        / 24.0
    )
    if m <= 2:
        y -= 1
        m += 12
    if (dt.year, dt.month, dt.day) >= (1582, 10, 15):
        a = y // 100
        b = 2 - a + a // 4
    else:
        b = 0
    return (
        math.floor(365.25 * (y + 4716))
        + math.floor(30.6001 * (m + 1))
        + day + b - 1524.5
    )


def jd_to_datetime(jd):
    """儒略日 → UTC datetime（tz-aware）。"""
    z = math.floor(jd + 0.5)
    f = (jd + 0.5) - z
    if z >= 2299161:
        alpha = math.floor((z - 1867216.25) / 36524.25)
        a = z + 1 + alpha - alpha // 4
    else:
        a = z
    b = a + 1524
    c = math.floor((b - 122.1) / 365.25)
    d = math.floor(365.25 * c)
    e = math.floor((b - d) / 30.6001)

    day_frac = b - d - math.floor(30.6001 * e) + f
    day = int(day_frac)
    month = e - 1 if e < 14 else e - 13
    year = c - 4716 if month > 2 else c - 4715

    rem = (day_frac - day) * SECONDS_PER_DAY
    # 四舍五入到微秒，避免 59.9999997 秒这类浮点残渣
    rem = round(rem, 6)
    return datetime(year, month, day, tzinfo=timezone.utc) + timedelta(seconds=rem)


# --------------------------------------------------------------------------
# ΔT = TT - UT，单位秒。Espenak & Meeus (NASA) 分段多项式。
# --------------------------------------------------------------------------

def delta_t(year, month=6):
    y = year + (month - 0.5) / 12.0

    if y < 1600:
        # 本项目不做古代盘，给个粗略值即可
        u = (y - 1820) / 100.0
        return -20 + 32 * u * u
    if y < 1700:
        t = y - 1600
        return 120 - 0.9808 * t - 0.01532 * t * t + t ** 3 / 7129.0
    if y < 1800:
        t = y - 1700
        return (
            8.83 + 0.1603 * t - 0.0059285 * t ** 2
            + 0.00013336 * t ** 3 - t ** 4 / 1174000.0
        )
    if y < 1860:
        t = y - 1800
        return (
            13.72 - 0.332447 * t + 0.0068612 * t ** 2 + 0.0041116 * t ** 3
            - 0.00037436 * t ** 4 + 0.0000121272 * t ** 5
            - 0.0000001699 * t ** 6 + 0.000000000875 * t ** 7
        )
    if y < 1900:
        t = y - 1860
        return (
            7.62 + 0.5737 * t - 0.251754 * t ** 2 + 0.01680668 * t ** 3
            - 0.0004473624 * t ** 4 + t ** 5 / 233174.0
        )
    if y < 1920:
        t = y - 1900
        return (
            -2.79 + 1.494119 * t - 0.0598939 * t ** 2
            + 0.0061966 * t ** 3 - 0.000197 * t ** 4
        )
    if y < 1941:
        t = y - 1920
        return 21.20 + 0.84493 * t - 0.076100 * t ** 2 + 0.0020936 * t ** 3
    if y < 1961:
        t = y - 1950
        return 29.07 + 0.407 * t - t ** 2 / 233.0 + t ** 3 / 2547.0
    if y < 1986:
        t = y - 1975
        return 45.45 + 1.067 * t - t ** 2 / 260.0 - t ** 3 / 718.0
    if y < 2005:
        t = y - 2000
        return (
            63.86 + 0.3345 * t - 0.060374 * t ** 2 + 0.0017275 * t ** 3
            + 0.000651814 * t ** 4 + 0.00002373599 * t ** 5
        )
    if y < 2050:
        t = y - 2000
        return 62.92 + 0.32217 * t + 0.005589 * t * t
    if y < 2150:
        u = (y - 1820) / 100.0
        return -20 + 32 * u * u - 0.5628 * (2150 - y)
    u = (y - 1820) / 100.0
    return -20 + 32 * u * u


