def _series(terms, tau):
    return sum(a * math.cos(b + c * tau) for a, b, c in terms)


def _poly(series_list, tau):
    total = 0.0
    for power, terms in enumerate(series_list):
        total += _series(terms, tau) * (tau ** power)
    return total / 1e8


