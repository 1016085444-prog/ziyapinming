# 太阳视黄经
# --------------------------------------------------------------------------

def _nutation_longitude(t):
    """章动黄经分量 Δψ，单位度。简化式，精度约 0.5"。"""
    omega = math.radians(125.04452 - 1934.136261 * t)
    l_sun = math.radians(280.4665 + 36000.7698 * t)
    l_moon = math.radians(218.3165 + 481267.8813 * t)
    arcsec = (
        -17.20 * math.sin(omega)
        - 1.32 * math.sin(2 * l_sun)
        - 0.23 * math.sin(2 * l_moon)
        + 0.21 * math.sin(2 * omega)
    )
    return arcsec / 3600.0


def apparent_solar_longitude(jde):
    """给定力学时儒略日，返回太阳视黄经（度，0–360）。

    节气正是按视黄经每 15° 划分：春分 0°、立春 315°。
    """
    tau = (jde - J2000) / 365250.0
    t = (jde - J2000) / 36525.0

    l_helio = _poly([_L0, _L1, _L2, _L3, _L4, _L5], tau)  # 弧度
    b_helio = _poly([_B0, _B1], tau)
    r = _poly([_R0, _R1, _R2, _R3, _R4], tau)  # AU

    # 日心 → 地心
    theta = math.degrees(l_helio) + 180.0
    beta = -math.degrees(b_helio)

    # VSOP87 → FK5 修正
    lam_p = math.radians(theta - 1.397 * t - 0.00031 * t * t)
    theta += -0.09033 / 3600.0
    beta += 0.03916 * (math.cos(lam_p) - math.sin(lam_p)) / 3600.0

    # 章动 + 光行差
    theta += _nutation_longitude(t)
    theta += -20.4898 / (3600.0 * r)

    return theta % 360.0


def _mean_anomaly_time_for(target_deg, jd_guess):
    """牛顿法反解 apparent_solar_longitude(jde) == target_deg。"""
    jde = jd_guess
    for _ in range(20):
        lon = apparent_solar_longitude(jde)
        diff = (target_deg - lon + 180.0) % 360.0 - 180.0
        if abs(diff) < 1e-9:
            break
        # 太阳日均行 ~0.9856°/日，用它作导数足够收敛
        jde += diff / 0.9856473
    return jde


def solar_term_jd(year, index):
    """第 `index` 个节气在 `year` 年的时刻，返回 UT 儒略日。

    index 0 = 立春（视黄经 315°），此后每 +1 即 +15°，共 24 个，
    顺序为 立春→雨水→惊蛰→…→大寒。
    """
    target = (315.0 + index * 15.0) % 360.0
    # 立春约在 2/4，之后每节气约隔 15.22 日
    approx = datetime(year, 2, 4, tzinfo=timezone.utc) + timedelta(
        days=15.2184 * index
    )
    jde = _mean_anomaly_time_for(target, julian_day(approx))
    dt_sec = delta_t(jd_to_datetime(jde).year)
    return jde - dt_sec / SECONDS_PER_DAY


def equation_of_time(jd_ut):
    """均时差（真太阳时 − 平太阳时），单位分钟。

    真太阳时校正的第二项。第一项是经度时差，在 chart 层处理。
    """
    t = (jd_ut - J2000) / 36525.0
    jde = jd_ut + delta_t(jd_to_datetime(jd_ut).year) / SECONDS_PER_DAY

    # 太阳平黄经
    l0 = (
        280.4664567 + 360007.6982779 * (t / 10) + 0.03032028 * (t / 10) ** 2
        + (t / 10) ** 3 / 49931 - (t / 10) ** 4 / 15300 - (t / 10) ** 5 / 2000000
    ) % 360.0

    lam = apparent_solar_longitude(jde)

    # 黄赤交角（含章动，Meeus 22.2 + 简化 Δε）
    u = t / 100.0
    eps0 = (
        23.43929111 - 1.30025833 * u - 0.00043056 * u ** 2 + 1.5555 * u ** 3
    )  # 度，主项
    omega = math.radians(125.04452 - 1934.136261 * t)
    eps = eps0 + (9.20 * math.cos(omega) + 0.57 * math.cos(
        math.radians(2 * (280.4665 + 36000.7698 * t))
    )) / 3600.0

    lam_r = math.radians(lam)
    eps_r = math.radians(eps)
    alpha = math.degrees(
        math.atan2(math.cos(eps_r) * math.sin(lam_r), math.cos(lam_r))
    ) % 360.0

    e = l0 - 0.0057183 - alpha + _nutation_longitude(t) * math.cos(eps_r)
    e = (e + 180.0) % 360.0 - 180.0
    return e * 4.0  # 度 → 分钟
