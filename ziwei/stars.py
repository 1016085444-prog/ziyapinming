# 三合局：安火铃、天马、将星等一大批星都以此分组
_TRINE_GROUPS = ("申子辰", "亥卯未", "寅午戌", "巳酉丑")


def _trine_of(branch):
    for g in _TRINE_GROUPS:
        if branch in g:
            return g
    raise ValueError("非法地支：{}".format(branch))


