def month_stars(lunar_month):
    """农历月决定的星曜位置。lunar_month 为 1–12。"""
    m = lunar_month - 1
    return {
        "左辅": (4 + m) % 12,               # 辰宫起正月顺行
        "右弼": (10 - m) % 12,              # 戌宫起正月逆行
        "天刑": (9 + m) % 12,               # 酉宫起正月顺行
        "天姚": (1 + m) % 12,               # 丑宫起正月顺行
        "阴煞": (2 - 2 * m) % 12,           # 寅宫起正月，隔宫逆行
        "解神": (8 + 2 * (m // 2)) % 12,    # 申宫起正二月，每两月进两宫
        "天巫": BRANCHES.index(_TIANWU[m % 4]),
        "天月": BRANCHES.index(_TIANYUE_MONTH[m]),
    }


