def day_stars(lunar_day, zuofu, youbi, wenchang, wenqu):
    """农历日决定的星曜位置。四个入参为对应辅星已定的宫序号。"""
    d = lunar_day - 1
    return {
        "三台": (zuofu + d) % 12,           # 左辅宫起初一顺行
        "八座": (youbi - d) % 12,           # 右弼宫起初一逆行
        "恩光": (wenchang + d - 1) % 12,    # 文昌宫起初一顺行，至生日退一步
        "天贵": (wenqu + d - 1) % 12,
    }


