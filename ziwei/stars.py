def _group_lookup(table, branch):
    for key, value in table.items():
        if branch in key:
            return value
    raise ValueError("表中无 {}".format(branch))


def year_branch_stars(year_branch, hour_index):
    """年支决定的星曜位置（火铃还需生时）。返回 {星名: 宫序号}。"""
    yb = BRANCHES.index(year_branch)
    trine = _trine_of(year_branch)

    huo = (BRANCHES.index(_HUOXING_START[trine]) + hour_index) % 12
    ling = (BRANCHES.index(_LINGXING_START[trine]) + hour_index) % 12

    hongluan = (3 - yb) % 12
    return {
        "天马": BRANCHES.index(_TIANMA[trine]),
        "火星": huo,
        "铃星": ling,
        "红鸾": hongluan,
        "天喜": (hongluan + 6) % 12,
        "孤辰": BRANCHES.index(_group_lookup(_GUCHEN, year_branch)),
        "寡宿": BRANCHES.index(_group_lookup(_GUASU, year_branch)),
        # 自午宫起子，天哭逆行、天虚顺行，故子年二星同落午宫
        "天哭": (6 - yb) % 12,
        "天虚": (6 + yb) % 12,
        "龙池": (4 + yb) % 12,
        "凤阁": (10 - yb) % 12,
        "破碎": BRANCHES.index(_group_lookup(_POSUI, year_branch)),
        "华盖": BRANCHES.index(_HUAGAI[trine]),
        "咸池": BRANCHES.index(_XIANCHI[trine]),
        "蜚廉": BRANCHES.index(_FEILIAN[year_branch]),
    }


