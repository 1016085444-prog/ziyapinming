_CHANGSHENG_START = {2: "申", 3: "亥", 4: "巳", 5: "申", 6: "寅"}


def _ring(start_index, names, forward):
    """把一组十二神套在十二宫上。返回 {宫序号: 神名}。"""
    step = 1 if forward else -1
    return {(start_index + step * i) % 12: name
            for i, name in enumerate(names)}


def changsheng_cycle(ju, forward):
    """长生十二神。forward 由阳男阴女（顺）／阴男阳女（逆）决定。"""
    return _ring(BRANCHES.index(_CHANGSHENG_START[ju]), CHANGSHENG_NAMES, forward)


