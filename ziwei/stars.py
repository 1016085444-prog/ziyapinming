# 量化亮度，供格局判断与评分取用。陷不给 0：星曜落陷是「用法要换」，
# 不是「不存在」，给 0 会让下游的加权失去区分度。
BRIGHTNESS_RANK = {"庙": 5, "旺": 4, "得": 3, "利": 2, "平": 1, "陷": 0}


def brightness(star, branch_index):
    """主星在某宫的亮度。非十四主星返回 None（辅星不论庙旺）。"""
    row = _BRIGHTNESS.get(star)
    return row[branch_index % 12] if row else None


# --------------------------------------------------------------------------
# 五行局
#
# 由命宫干支的纳音定，决定紫微星的落点与大限起运岁数。
# 一张盘的骨架就是「五行局 + 生日」这两个数。
# --------------------------------------------------------------------------

FIVE_PHASE_JU = {
    "水": (2, "水二局"), "木": (3, "木三局"), "金": (4, "金四局"),
    "土": (5, "土五局"), "火": (6, "火六局"),
}


def palace_stem(year_stem, branch_index):
    """宫干：五虎遁，自寅宫起排。

    十二宫配十个天干，故子、丑两宫会与寅、卯重复——这不是 bug，
    传统排法本就如此（甲年寅宫丙寅，绕回子宫仍是丙子）。
    """
    base = ((STEMS.index(year_stem) % 5) * 2 + 2) % 10   # 寅宫之干
    steps = (branch_index - 2) % 12                      # 自寅宫顺数的步数
    return STEMS[(base + steps) % 10]


def five_phase_ju(year_stem, life_palace_index):
    """命宫纳音 → (局数, 局名)。"""
    stem = palace_stem(year_stem, life_palace_index)
    element = nayin(stem, BRANCHES[life_palace_index])[-1]
    return FIVE_PHASE_JU[element]


# --------------------------------------------------------------------------
# 紫微与天府：十四主星的两个锚点
# --------------------------------------------------------------------------

def ziwei_index(lunar_day, ju):
    """安紫微星：由五行局数与农历日定位。

    传统「借数」法：把生日凑成局数的整数倍，商数自寅宫顺数；
    所借之数为偶则再顺进、为奇则逆退。例如金四局初一，借 3 凑成 4，
    商 1（寅宫），借数为奇故逆退 3 位 → 亥宫。
    """
    n = 0
    while (lunar_day + n) % ju:
        n += 1
    quotient = (lunar_day + n) // ju
    pos = 2 + (quotient - 1)                      # 自寅宫起数商
    return (pos + (n if n % 2 == 0 else -n)) % 12


def tianfu_index(ziwei_idx):
    """天府与紫微以寅申为轴对称：紫微在寅（申）则天府同宫，余则相向而行。"""
    return (4 - ziwei_idx) % 12


# 两系星曜相对锚点的位移。紫微系逆行、天府系顺行，串内间距是固定的。
_ZIWEI_SERIES = (
    ("紫微", 0), ("天机", -1), ("太阳", -3),
    ("武曲", -4), ("天同", -5), ("廉贞", -8),
)
_TIANFU_SERIES = (
    ("天府", 0), ("太阴", 1), ("贪狼", 2), ("巨门", 3),
    ("天相", 4), ("天梁", 5), ("七杀", 6), ("破军", 10),
)


def major_star_positions(lunar_day, ju):
    """十四主星的宫位。返回 {星名: 宫序号}。"""
    zw = ziwei_index(lunar_day, ju)
    tf = tianfu_index(zw)
    out = {name: (zw + off) % 12 for name, off in _ZIWEI_SERIES}
    out.update({name: (tf + off) % 12 for name, off in _TIANFU_SERIES})
    return out


