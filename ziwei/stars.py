def hour_stars(hour_index):
    """生时决定的星曜位置。hour_index 为 0–11（0 = 子时）。"""
    return {
        # 「子时戌上起文昌，逆到生时是贵乡；文曲数从辰上起，顺到生时是本乡」
        "文昌": (10 - hour_index) % 12,
        "文曲": (4 + hour_index) % 12,
        # 「亥上子时安地劫，逆回便是地空亡」——同起亥宫，一顺一逆
        "地劫": (11 + hour_index) % 12,
        "地空": (11 - hour_index) % 12,
        "台辅": (6 + hour_index) % 12,
        "封诰": (2 + hour_index) % 12,
    }


